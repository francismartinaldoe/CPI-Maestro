def _load_cpi_team():
    """Load team from config/team.json — populate before running."""
    cfg = os.path.join(os.path.dirname(__file__), '..', 'config', 'team.json')
    try:
        with open(cfg, encoding='utf-8') as f:
            team = json.load(f).get('team', [])
        names = set()
        for m in team:
            n = m.get('name', '').strip().lower()
            if n:
                names.add(n)
                parts = n.split()
                if len(parts) >= 2:
                    names.add(f"{parts[-1]}, {' '.join(parts[:-1])}")
        return names
    except FileNotFoundError:
        return set()

