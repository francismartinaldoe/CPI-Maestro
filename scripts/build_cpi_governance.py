def fmt_date(iso):
    if not iso:
        return ""
    try:
        d = datetime.fromisoformat(iso.replace("Z",""))
        return f"{d.day:02d}/{MONTHS[d.month-1]}/{d.year}"
    except:
        return iso

def days_ago(iso, today):
    if not iso:
        return None
    try:
        d = datetime.fromisoformat(iso.replace("Z",""))
        if d.tzinfo is None:
            d = d.replace(tzinfo=timezone.utc)
        return (today - d).days
    except:
        return None

def clean_comment(body):
    if not body:
        return ""
    body = re.sub(r'\[~[^\]]+\]', '', body)
    body = re.sub(r'!\S+\.(png|jpg|gif)!', '', body, flags=re.I)
    body = re.sub(r'\{[^}]+\}', '', body)
    body = re.sub(r'\*([^*]+)\*', r'\1', body)
    body = re.sub(r'\s+', ' ', body).strip()
    return body[:300]

def extract_last_comment(comments, today):
    if not comments:
        return {"text":"","by":"","date":"","days_ago":None,"has24h":"No"}
    last = comments[-1]
    body = clean_comment(last.get("body",""))
    author_obj = last.get("author", {})
    author = author_obj.get("display_name", author_obj.get("displayName", ""))
    author = re.sub(r'\s*\(external[^)]*\)','', author).strip()
    created = last.get("created", last.get("updated", ""))
    da = days_ago(created, today)
    return {
        "text": body,
        "by": author,
        "date": fmt_date(created),
        "days_ago": da,
        "has24h": "Yes" if da is not None and da <= 1 else "No"
    }

def extract_pdd(field):
    if not field:
        return ""
    val = field.get("value", field) if isinstance(field, dict) else field
    if isinstance(val, list) and val:
        val = val[0]
    return fmt_date(str(val)) if val else ""

def extract_sprint(field):
    if not field:
        return ""
    arr = field.get("value", field) if isinstance(field, dict) else field
    if not isinstance(arr, list) or not arr:
        return ""
    last = arr[-1]
    if isinstance(last, str):
        m = re.search(r'name=([^,\]]+)', last)
        return m.group(1).strip() if m else ""
    return str(last)

def extract_commit(labels):
    ll = [l.lower() for l in (labels or [])]
    if "committed" in ll:
        return "Committed"
    if "uncommitted" in ll:
        return "Uncommitted"
    return ""

def strip_external(name):
    if not name:
        return ""
    return re.sub(r'\s*\(external[^)]*\)','', name).strip()

def suggest_sprint(today):
    for name, start, end in PI263_SPRINTS:
        if start.date() <= today.date() <= end.date():
            return f"Suggested: {name}"
        if today.date() < start.date():
            return f"Suggested: {name}"
    return ""

