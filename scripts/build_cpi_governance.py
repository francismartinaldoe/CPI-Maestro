CACHE_MAX_AGE_HOURS = 4


def main():
    parser = argparse.ArgumentParser(description="Build CPI ART Governance Workbook")
    parser.add_argument("positional_data", nargs="?", help="Path to jira_data.json (positional)")
    parser.add_argument("positional_out",  nargs="?", help="Output .xlsx path (positional)")
    parser.add_argument("--data",      help="Path to jira_data.json")
    parser.add_argument("--out",       help="Output .xlsx path")
    parser.add_argument("--cleanup",   action="store_true", help="Delete input JSON after successful build")
    parser.add_argument("--use-cache", action="store_true",
                        help=f"Reuse existing jira_data.json if it is less than {CACHE_MAX_AGE_HOURS}h old — skips JIRA fetch")
    args = parser.parse_args()

    data_path   = args.data    or args.positional_data
    output_path = args.out     or args.positional_out

    if not data_path or not output_path:
        parser.print_help()
        sys.exit(1)

    # Cache check: if --use-cache and file is fresh enough, skip JIRA fetch and reuse it
    cache_used = False
    if args.use_cache and os.path.exists(data_path):
        age_seconds = datetime.now(timezone.utc).timestamp() - os.path.getmtime(data_path)
        age_hours = age_seconds / 3600
        if age_hours < CACHE_MAX_AGE_HOURS:
            print(f"[cache] Reusing {data_path} ({age_hours:.1f}h old — within {CACHE_MAX_AGE_HOURS}h limit). Skipping JIRA fetch.")
            cache_used = True
        else:
            print(f"[cache] Cache expired ({age_hours:.1f}h old, limit {CACHE_MAX_AGE_HOURS}h). JIRA fetch required — rerun /cpi-governance without --use-cache.")
            sys.exit(1)
    elif args.use_cache and not os.path.exists(data_path):
        print(f"[cache] --use-cache set but {data_path} not found. Run /cpi-governance normally first to populate the cache.")
        sys.exit(1)

    with open(data_path, encoding="utf-8") as f:
        data = json.load(f)

    today = datetime.now(timezone.utc)
    timestamp = data.get("timestamp", today.strftime("%Y-%m-%d %H:%M"))

    # Parse all issues
    raw_cpi     = data.get("cpi_arts", [])
    raw_stories = data.get("stories", [])
    raw_streams = data.get("stream_arts", [])
    raw_orphans_q = data.get("orphan_candidates", [])

    cpi_arts  = [parse_art(i, today) for i in raw_cpi]
    all_stories = [parse_story(i, today) for i in raw_stories]
    stream_data = {parse_art(i, today)["key"]: parse_art(i, today) for i in raw_streams}

    # Build stream lookup: CPI key → Stream key
    stream_by_cpi = {}
    for art in cpi_arts:
        sk = find_stream_art(art["links"], stream_data)
        if sk:
            stream_by_cpi[art["key"]] = sk

    stream_map = {"by_cpi": stream_by_cpi, "data": stream_data}

    # Build stories_by_art: match stories to CPI ARTs via parent link
    stories_by_art = {a["key"]: [] for a in cpi_arts}
    for story in all_stories:
        if story["parent_art"] and story["parent_art"] in stories_by_art:
            stories_by_art[story["parent_art"]].append(story)

    # Orphan detection
    SECONDARY = {"INT-CPI","YOUR-TEAM-LABEL","Interface_Build","IF_Type_CPI"}
    orphans = []
    for issue in raw_orphans_q:
        s = parse_story(issue, today)
        labels_set = set(s["labels"])
        if "RICEFW" not in labels_set:
            continue
        if not labels_set & SECONDARY:
            continue
        has_art_parent = any(
            (link.get("inward_issue") or link.get("inwardIssue") or {}).get("key","").startswith("YOUR_JIRA_PROJECT-") or
            (link.get("outward_issue") or link.get("outwardIssue") or {}).get("key","").startswith("YOUR_JIRA_PROJECT-")
            for link in s["links"]
            if "parent" in (link.get("type",{}).get("name","")).lower()
        )
        if has_art_parent:
            continue
        # Find non-CPI parent
        non_cpi = ""
        orphan_type = "no_parent"
        for link in s["links"]:
            lt = (link.get("type",{}).get("name","")).lower()
            if "parent" in lt:
                li_key = (link.get("inward_issue") or link.get("inwardIssue") or {}).get("key","")
                lo_key = (link.get("outward_issue") or link.get("outwardIssue") or {}).get("key","")
                for k in [li_key, lo_key]:
                    if k and not k.startswith("YOUR_JIRA_PROJECT-"):
                        non_cpi = k
                        orphan_type = "non_cpi_parent"
        s["orphan_type"] = orphan_type
        s["non_cpi_parent"] = non_cpi
        orphans.append(s)

    # Suggested sprint for today
    suggested_sprint = suggest_sprint(today)

    # Group CPI ARTs by release
    releases = {}
    for art in cpi_arts:
        r = art["release"] or "(No Release)"
        releases.setdefault(r, []).append(art)

    # Sort by sort key
    sorted_releases = sorted(releases.keys(), key=release_sort_key)

    # Build workbook
    wb = Workbook()
    wb.remove(wb.active)  # remove default sheet

    # Sheet 1: Dashboard
    ws_dash = wb.create_sheet("Dashboard")
    build_dashboard(ws_dash, cpi_arts, stories_by_art, stream_map, timestamp, today)

    # Sheet 2: MASTER_REPORT
    ws_master = wb.create_sheet("MASTER_REPORT")
    build_master_report(ws_master, cpi_arts, stories_by_art, stream_map, timestamp, today, suggested_sprint)

    # Sheet 3: Incompleteness Check
    ws_inc = wb.create_sheet("Incompleteness Check")
    build_incompleteness(ws_inc, cpi_arts, stories_by_art, stream_map, timestamp, today)

    # Sheet 4: ART-YOUR_JIRA_PROJECT Mapping
    ws_map = wb.create_sheet("ART-YOUR_JIRA_PROJECT Mapping")
    build_mapping(ws_map, cpi_arts, stories_by_art, stream_map, timestamp, today)

    # Sheets 5+: Dynamic release sheets
    for i, release in enumerate(sorted_releases):
        sheet_name = release.replace(".","_").replace(" ","_").replace("(","").replace(")","")[:31]
        ws_rel = wb.create_sheet(sheet_name)
        tab_colour = RELEASE_TAB_COLOURS[i % len(RELEASE_TAB_COLOURS)]
        build_release_sheet(ws_rel, release, releases[release], stories_by_art, stream_map, timestamp, today, tab_colour, suggested_sprint)

    # Intelligence Signals
    ws_sig = wb.create_sheet("Intelligence Signals")
    build_intelligence_signals(ws_sig, cpi_arts, stories_by_art, stream_map, timestamp, today)

    # Stream Action Register
    ws_sar = wb.create_sheet("Stream Action Register")
    build_stream_actions(ws_sar, cpi_arts, stories_by_art, stream_map, timestamp, today)

    # Raw Data
    ws_raw = wb.create_sheet("Raw Data")
    build_raw_data(ws_raw, cpi_arts, stories_by_art, stream_map, timestamp, today)

    # Story Compliance Matrix
    ws_comp = wb.create_sheet("Story Compliance")
    build_story_compliance(ws_comp, cpi_arts, stories_by_art, stream_map, timestamp, today)

    # Hierarchy Tree (Stream ART → CPI ART → YOUR_JIRA_PROJECT)
    ws_tree = wb.create_sheet("Hierarchy Tree")
    build_hierarchy_tree(ws_tree, cpi_arts, stories_by_art, stream_map, timestamp, today)

    # Orphan CPI Stories
    ws_orp = wb.create_sheet("Orphan CPI Stories")
    build_orphan_sheet(ws_orp, orphans, timestamp, today)

    # Save
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    wb.save(output_path)

    # Cleanup input JSON if requested — skip when cache was reused (keep it for next run)
    if args.cleanup and not cache_used and os.path.exists(data_path):
        os.remove(data_path)

    # Summary
    cache_note = f" (from cache)" if cache_used else ""
    file_kb = os.path.getsize(output_path) // 1024
    story_count = sum(len(v) for v in stories_by_art.values())
    sep = "-" * 52
    sys.stdout.buffer.write((
        f"\n{sep}\n"
        f"CPI ART Governance Workbook - Generated\n"
        f"{sep}\n"
        f"File:      {output_path}\n"
        f"Size:      {file_kb} KB\n"
        f"Generated: {timestamp}{cache_note}\n"
        f"\n"
        f"Data fetched live from SAP Jira:\n"
        f"  CPI ARTs (INT-CPI):      {len(cpi_arts)}\n"
        f"  YOUR_JIRA_PROJECT Stories:       {story_count}\n"
        f"  Stream ARTs linked:      {len(stream_data)}\n"
        f"  Orphan candidates:       {len(orphans)}\n"
        f"\n"
        f"Sheets built:              {len(wb.sheetnames)}\n"
    ).encode('utf-8'))
    for ws in wb.worksheets:
        sys.stdout.buffer.write(f"    {ws.title}: {ws.max_row} rows\n".encode('utf-8'))
    sys.stdout.buffer.write((
        f"{sep}\n"
        f"Open the file in Excel to view the report.\n"
    ).encode('utf-8'))
    sys.stdout.buffer.flush()


if __name__ == "__main__":
    main()
