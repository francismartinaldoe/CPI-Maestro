_NA_TOKENS = {"n/a", "na", "tbd", "not applicable"}

def _section_status(desc_lower, marker1, marker2):
    """Return 'present', 'na', or 'missing'."""
    i1 = desc_lower.find(marker1)
    if i1 < 0:
        return "missing"
    if marker2:
        i2 = desc_lower.find(marker2, i1, i1 + 300)
        if i2 < 0:
            return "missing"
        after = desc_lower[i2 + len(marker2): i2 + len(marker2) + 400].strip()
    else:
        after = desc_lower[i1 + len(marker1): i1 + len(marker1) + 400].strip()
    # N/A check: first 80 chars of section body
    head = after[:80].replace(" ", "").replace("\n", "").replace("\r", "")
    if any(t in head for t in _NA_TOKENS) or head in ("", "<>", "—"):
        return "na"
    return "present"

def check_story_compliance(story):
    """Return compliance dict for one story."""
    labels = set(story.get("labels") or [])
    desc   = (story.get("description") or "").lower()
    prio   = story.get("priority") or ""

    meta = {
        "M1_IF_Type_CPI":     "IF_Type_CPI" in labels,
        "M2_RICEFW":          "RICEFW" in labels,
        "M3_Interface_Build": "Interface_Build" in labels,
        "M4_Priority":        bool(prio),
        "M5_Version":         bool(story.get("release")),
        "M6_Sprint":          bool(story.get("sprint")),
        "M7_Dev_Ready":       story.get("status","").lower() == "development ready",
        "M8_Component":       bool(story.get("comp")),
    }

    sections = {}
    for sid, m1, m2, _ in SECTION_PATTERNS:
        sections[sid] = _section_status(desc, m1.lower(), m2.lower())

    meta_pass   = sum(1 for v in meta.values() if v)
    sec_pass    = sum(1 for v in sections.values() if v == "present")
    sec_na      = sum(1 for v in sections.values() if v == "na")
    total_gates = len(meta) + len(sections)
    score_pct   = (meta_pass + sec_pass + sec_na * 0.5) / total_gates * 100
    rag = "Green" if score_pct >= 90 else "Amber" if score_pct >= 70 else "Red"
    return {
        "meta": meta, "sections": sections,
        "score_pct": round(score_pct, 1), "rag": rag,
        "meta_pass": meta_pass, "sec_pass": sec_pass, "sec_na": sec_na,
    }

