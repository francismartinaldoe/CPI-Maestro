def derive_intelligence_signals(art, stories, stream, today):
    signals = []
    status_l = art["status"].lower()

    # STORIES NOT CLOSED — always check even for Done ARTs
    if art["is_done"]:
        open_stories = [s for s in stories if not s["is_closed"]]
        if open_stories:
            for s in open_stories:
                signals.append({
                    "type": "\U0001f534 STORIES NOT CLOSED",
                    "detail": f"ART is Done but {len(open_stories)} story/stories still open",
                    "urgency": "Red",
                    "story": s
                })
        return signals  # Done ARTs get no other signals

    pdd_date = None
    if art["pdd"]:
        try:
            pdd_date = datetime.strptime(art["pdd"], "%d/%b/%Y").replace(tzinfo=timezone.utc)
        except:
            pass

    if pdd_date:
        days_to_pdd = (pdd_date - today).days
        if days_to_pdd < 0:
            signals.append({"type":"\U0001f6a8 PDD OVERDUE","detail":f"PDD {art['pdd']} passed","urgency":"Red","story":None})
        elif days_to_pdd <= 7:
            signals.append({"type":"⚠️ PDD APPROACHING","detail":f"{days_to_pdd}d until PDD","urgency":"Amber","story":None})
        elif days_to_pdd <= 14 and not any(s["is_closed"] for s in stories):
            signals.append({"type":"⚠️ PDD RISK","detail":"0 children done within 14d of PDD","urgency":"Amber","story":None})

    if art["is_comment_check"]:
        active = [s for s in stories if not s["is_closed"]]
        if not stories:
            da = art["lc"]["days_ago"]
            if da is not None and da > 7:
                urg = "Red" if da > 14 else "Amber"
                signals.append({"type":"⏸ STALE (No Stories)","detail":f"No child stories; ART not updated for {da}d","urgency":urg,"story":None})
        elif active:
            stale = [s for s in active if s["lc"]["days_ago"] is not None and s["lc"]["days_ago"] > 7]
            if len(stale) == len(active):
                worst = max(s["lc"]["days_ago"] for s in stale)
                urg = "Red" if worst > 14 else "Amber"
                signals.append({"type":"⏸ STALE","detail":f"All {len(active)} active stories not updated for 7+ days","urgency":urg,"story":stale[0]})
            elif stale:
                signals.append({"type":"⏸ PARTIAL STALE","detail":f"{len(stale)}/{len(active)} active stories stale","urgency":"Amber","story":stale[0]})

    if art["commit"] == "Committed":
        milestone = derive_milestone(art, stories)
        if milestone in ("In Design","In Analysis"):
            signals.append({"type":"\U0001f3af COMMITTED/NOT STARTED","detail":"Committed but no build activity","urgency":"Amber","story":None})

    blocked = [s for s in stories if s["status"].lower() == "blocked"]
    if blocked:
        urg = "Red" if art["commit"] == "Committed" else "Amber"
        signals.append({"type":"⛔ BLOCKED","detail":f"{len(blocked)} story/stories blocked: {', '.join(s['key'] for s in blocked)}","urgency":urg,"story":blocked[0]})

    if not stories and art["is_comment_check"]:
        signals.append({"type":"❓ NO STORIES","detail":"Active ART has no YOUR_JIRA_PROJECT children","urgency":"Red","story":None})

    done_stories = [s for s in stories if s["is_closed"]]
    pct = len(done_stories)/len(stories)*100 if stories else 0
    if pdd_date and (pdd_date - today).days <= 21 and pct < 50:
        signals.append({"type":"\U0001f4c9 LOW COMPLETION","detail":f"{pct:.0f}% done within 21d of PDD","urgency":"Amber","story":None})

    if stream and not stream["commit"]:
        signals.append({"type":"\U0001f517 STREAM UNCOMMITTED","detail":"Stream ART has no commitment label","urgency":"Amber","story":None})

    if stream and stream["commit"] == "Committed" and art["status"].lower() == "new":
        signals.append({"type":"⚡ STREAM AHEAD","detail":"Stream Committed but CPI ART still New","urgency":"Amber","story":None})

    return signals

def derive_stream_actions(art, stream, stories, today):
    actions = []
    if not stream:
        actions.append({"action":"LINK STREAM ART","detail":"No Stream ART linked to this CPI ART","urgency":"Red","escalate":art["assignee"]})
        return actions
    if not stream["commit"]:
        actions.append({"action":"SET COMMITMENT","detail":"Stream ART has no Committed/Uncommitted label","urgency":"Amber","escalate":stream["assignee"]})
    if not stream["bgl"] and not stream["tgl"]:
        actions.append({"action":"ADD BGL OR TGL LABEL","detail":f"Stream ART {stream['key']} has neither a BGL nor TGL label. At least one required.","urgency":"Amber","escalate":stream["assignee"]})
    if not stream["release"]:
        actions.append({"action":"SET RELEASE","detail":"Stream ART has no fix version set","urgency":"Amber","escalate":stream["assignee"]})
    if not stream["pdd"]:
        actions.append({"action":"SET PDD","detail":"Stream ART has no PDD set","urgency":"Amber","escalate":stream["assignee"]})
    da = stream["lc"]["days_ago"]
    if da is not None and da > 7 and stream["status"].lower() not in DONE_STATUSES:
        urg = "Red" if da > 14 else "Amber"
        actions.append({"action":"REQUEST STATUS UPDATE","detail":f"Stream ART {stream['key']} not updated for {da}d","urgency":urg,"escalate":stream["assignee"]})
    if stream["commit"] == "Committed" and stream["status"].lower() not in ("in development","in progress") and stream["status"].lower() not in DONE_STATUSES:
        actions.append({"action":"ESCALATE STATUS MISMATCH","detail":"Committed but status not In Dev/Done","urgency":"Red","escalate":stream["assignee"]})
    blocked = [s for s in stories if s["status"].lower() == "blocked"]
    if blocked and stream["commit"] == "Committed":
        actions.append({"action":"UNBLOCK STORY","detail":f"Blocked: {', '.join(s['key'] for s in blocked)}","urgency":"Red","escalate":art["assignee"]})
    return actions

