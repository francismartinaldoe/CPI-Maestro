    ws.tab_color = "607D8B"

    HEADERS = [
        ("Stream ART","37474F"),("Stream Status","37474F"),("Stream Commitment","37474F"),
        ("Stream BGL","37474F"),("Stream TGL","37474F"),("Stream Sprint","37474F"),
        ("Stream PDD","37474F"),("Stream Last Comment","37474F"),("Stream Commented By","37474F"),
        ("Stream Comment Date","37474F"),
        ("CPI ART ID","37474F"),("Summary","37474F"),("Status","37474F"),
        ("Status Category","37474F"),("Release","37474F"),("CPI Commitment","37474F"),
        ("Owner","37474F"),("Component","37474F"),("Created By","37474F"),
        ("Sprint","37474F"),("PDD","37474F"),("CPI Last Comment","37474F"),
        ("CPI Commented By","37474F"),("CPI Comment Date","37474F"),("CPI 24Hr","37474F"),
        ("INT-CPI Label","37474F"),("BGL","37474F"),("TGL","37474F"),
        ("Labels","37474F"),("Updated","37474F"),
        ("YOUR_JIRA_PROJECT Count","37474F"),("Story Keys","37474F"),
        ("Milestone","37474F"),("Health","37474F"),("Issues Count","37474F"),
        ("CPI Incompleteness","37474F"),
    ]
    apply_header(ws, 1, HEADERS)
    ws.freeze_panes = "A2"
    enable_autofilter(ws, 1, len(HEADERS))

    for ri, art in enumerate(cpi_arts):
        stream_key = stream_map.get("by_cpi",{}).get(art["key"],"")
        stream = stream_map.get("data",{}).get(stream_key)
        stories = stories_by_art.get(art["key"],[])
        milestone = derive_milestone(art, stories)
        cpi_inc = derive_cpi_incompleteness(art, stories, stream_key, today)
        s_inc = derive_stream_incompleteness(stream)
        inc_count = len([x for x in cpi_inc.split(";") if x.strip()]) + len([x for x in s_inc.split(";") if x.strip()])
        hf, _ = health_fill(inc_count)
        row = ri + 2
        row_bg = "FAFAFA" if ri%2==1 else "FFFFFF"

        vals = [
            stream["key"] if stream else "",
            stream["status"] if stream else "",
            stream["commit"] if stream else "",
            stream["bgl"] if stream else "",
            stream["tgl"] if stream else "",
            stream["sprint"] if stream else "",
            stream["pdd"] if stream else "",
            stream["lc"]["text"][:100] if stream else "",
            stream["lc"]["by"] if stream else "",
            stream["lc"]["date"] if stream else "",
            art["key"], art["summary"], art["status"], art["status_cat"],
            art["release"], art["commit"], art["assignee"], art["comp"], art["creator"],
            art["sprint"], art["pdd"],
            art["lc"]["text"][:100], art["lc"]["by"], art["lc"]["date"], art["lc"]["has24h"],
            art["int_cpi"], art["bgl"], art["tgl"],
            ", ".join(art["labels"]), "",
            len(stories), ", ".join(s["key"] for s in stories),
            milestone,
            "Green" if inc_count==0 else "Amber" if inc_count<=2 else "Red",
            inc_count, cpi_inc,
        ]
        for col, val in enumerate(vals, 1):
            write_data_cell(ws, row, col, val, row_bg)
        ws.row_dimensions[row].height = 20

    autofit_headers(ws, 1)


