def parse_art(issue, today):
    # MCP returns flat issues (no 'fields' wrapper)
    labels = [l for l in (issue.get("labels") or []) if l]
    key = issue.get("key","")
    status_obj = issue.get("status") or {}
    status = status_obj.get("name","")
    status_cat = status_obj.get("category","")
    assignee_obj = issue.get("assignee") or {}
    assignee = strip_external(assignee_obj.get("display_name", assignee_obj.get("displayName","")))
    reporter_obj = issue.get("reporter") or {}
    reporter = strip_external(reporter_obj.get("display_name", reporter_obj.get("displayName","")))
    creator_obj = issue.get("creator") or {}
    creator  = strip_external(creator_obj.get("display_name", creator_obj.get("displayName","")))
    # fix_versions is a list of strings in MCP format
    raw_versions = issue.get("fix_versions") or issue.get("fixVersions") or []
    versions = [v if isinstance(v, str) else v.get("name","") for v in raw_versions]
    release  = versions[0] if versions else ""
    raw_comps = issue.get("components") or []
    comps    = [c if isinstance(c, str) else c.get("name","") for c in raw_comps]
    comp     = comps[0] if comps else ""
    bgl = next((l for l in labels if l.upper().startswith("BGLRD")), "")
    tgl = next((l for l in labels if l.upper().startswith("TGLRD")), "")
    commit = extract_commit(labels)
    int_cpi = "Yes" if "INT-CPI" in labels else "Missing"
    sprint  = extract_sprint(issue.get("customfield_12740"))
    pdd     = extract_pdd(issue.get("customfield_10253"))
    # comments is a flat list in MCP format
    comments = issue.get("comments") or []
    lc = extract_last_comment(comments, today)
    links = issue.get("issuelinks") or []
    return {
        "key": key,
        "summary": issue.get("summary",""),
        "status": status,
        "status_cat": status_cat,
        "assignee": assignee,
        "reporter": reporter,
        "creator": creator,
        "release": release,
        "comp": comp,
        "labels": labels,
        "bgl": bgl,
        "tgl": tgl,
        "commit": commit,
        "int_cpi": int_cpi,
        "sprint": sprint,
        "pdd": pdd,
        "lc": lc,
        "links": links,
        "is_done": status.lower() in DONE_STATUSES,
        "is_comment_check": status.lower() in COMMENT_CHECK_STATUSES,
    }

def parse_story(issue, today):
    # MCP returns flat issues (no 'fields' wrapper)
    labels = [l for l in (issue.get("labels") or []) if l]
    key = issue.get("key","")
    status_obj = issue.get("status") or {}
    status = status_obj.get("name","")
    assignee_obj = issue.get("assignee") or {}
    assignee = strip_external(assignee_obj.get("display_name", assignee_obj.get("displayName","")))
    reporter_obj = issue.get("reporter") or {}
    reporter = strip_external(reporter_obj.get("display_name", reporter_obj.get("displayName","")))
    raw_versions = issue.get("fix_versions") or issue.get("fixVersions") or []
    versions = [v if isinstance(v, str) else v.get("name","") for v in raw_versions]
    release  = versions[0] if versions else ""
    raw_comps = issue.get("components") or []
    comps    = [c if isinstance(c, str) else c.get("name","") for c in raw_comps]
    comp     = comps[0] if comps else ""
    sprint   = extract_sprint(issue.get("customfield_12740"))
    pdd      = extract_pdd(issue.get("customfield_10253"))
    comments = issue.get("comments") or []
    lc = extract_last_comment(comments, today)
    links = issue.get("issuelinks") or []
    parent_art = ""
    for link in links:
        li = link.get("inward_issue") or link.get("inwardIssue") or {}
        lo = link.get("outward_issue") or link.get("outwardIssue") or {}
        lt = (link.get("type") or {}).get("name","")
        for candidate in [li, lo]:
            k = candidate.get("key","")
            if k.startswith("YOUR_JIRA_PROJECT-") and "parent" in lt.lower():
                parent_art = k
                break
    description = issue.get("description") or ""
    priority_obj = issue.get("priority") or {}
    priority = priority_obj.get("name","") if isinstance(priority_obj, dict) else str(priority_obj)
    return {
        "key": key,
        "summary": issue.get("summary",""),
        "status": status,
        "assignee": assignee,
        "reporter": reporter,
        "release": release,
        "comp": comp,
        "labels": labels,
        "sprint": sprint,
        "pdd": pdd,
        "lc": lc,
        "links": links,
        "parent_art": parent_art,
        "is_closed": status.lower() in STORY_CLOSED_STATUSES,
        "description": description,
        "priority": priority,
    }

def find_stream_art(art_links, stream_lookup):
    """Find the linked Stream ART key from a CPI ART's issuelinks."""
    for link in art_links:
        lt = (link.get("type") or {}).get("name","")
        for direction in ["inward_issue","outward_issue","inwardIssue","outwardIssue"]:
            candidate = link.get(direction) or {}
            k = candidate.get("key","")
            if k.startswith("YOUR_JIRA_PROJECT-") and k in stream_lookup:
                if "split" in lt.lower() or "relation" in lt.lower():
                    return k
    return ""

def derive_milestone(art, stories):
    status = art["status"].lower()
    if status in DONE_STATUSES or status == "in releasing":
        return "Moved To Production"
    if status == "ready for deployment":
        return "Functional Sign Off"
    if status in ("validation","ready for validation"):
        return "Moved To Test"
    if any(s["status"].lower() == "verification" for s in stories):
        return "Unit Test Completed"
    if status == "development completed":
        return "Build Completed"
    if stories and all(s["status"].lower() in STORY_CLOSED_STATUSES for s in stories):
        return "Build Completed"
    if any(s["status"].lower() == "blocked" for s in stories):
        return "Build Blocked"
    if any(s["status"].lower() in ("in progress","development ready","in development","in refinement") for s in stories):
        return "Build Started"
    if status == "new" and not stories:
        return "In Design"
    return "In Analysis"

