def fill(hex_colour):
    return PatternFill("solid", fgColor=hex_colour)

def font(bold=False, colour="000000", size=10):
    return Font(bold=bold, color=colour, name="Calibri", size=size)

def header_font():
    return Font(bold=True, color="FFFFFF", name="Calibri", size=11)

def center():
    return Alignment(horizontal="center", vertical="center", wrap_text=True)

def left():
    return Alignment(horizontal="left", vertical="top", wrap_text=True)

def thin_border():
    s = Side(style="thin", color=C_BORDER)
    return Border(left=s, right=s, top=s, bottom=s)

def medium_left_border():
    s = Side(style="medium", color=C_DARK_BLUE)
    return Border(left=s)

def apply_header(ws, row_num, headers, fills=None, start_col=1):
    """Write a header row with group fills. headers = [(text, fill_hex), ...]"""
    for i, (text, fill_hex) in enumerate(headers, start_col):
        c = ws.cell(row=row_num, column=i, value=text)
        c.fill = fill(fill_hex)
        c.font = header_font()
        c.alignment = center()
        c.border = thin_border()

def set_col_widths(ws, widths):
    """widths = {col_letter: width}"""
    for col, w in widths.items():
        ws.column_dimensions[col].width = w

def autofit_headers(ws, row_num):
    """Set minimum column width based on header text length."""
    for cell in ws[row_num]:
        if cell.value:
            col = get_column_letter(cell.column)
            current = ws.column_dimensions[col].width
            needed = min(max(len(str(cell.value)) * 1.1 + 2, 10), 40)
            if needed > current:
                ws.column_dimensions[col].width = needed

def write_data_cell(ws, row, col, value, fill_hex=None, bold=False,
                    fg=None, wrap=True, number_fmt=None):
    c = ws.cell(row=row, column=col, value=value)
    if fill_hex:
        c.fill = fill(fill_hex)
    if bold or fg:
        c.font = Font(bold=bold, color=fg or "000000", name="Calibri", size=10)
    c.alignment = Alignment(horizontal="left", vertical="top", wrap_text=wrap)
    c.border = thin_border()
    if number_fmt:
        c.number_format = number_fmt
    return c

